#!/usr/bin/env python3
"""
Conditional DSBM baseline for the official PDEBench 2D diffusion-reaction
parameter-intervention benchmark generated by
pdebench_reaction_diffusion_official.py.

State is kept in full spatial form [B,2,128,128].  The drift is a compact U-Net
conditioned on the three intervention coordinates and bridge time.  No response
supervision is used in this script; directional JVP response is evaluation-only.

The IMF / reciprocal bridge formulas mirror the Gaussian and double-well
experiments.  The only architecture change is MLP -> spatial U-Net.
"""

from __future__ import annotations
import argparse, csv, json, logging, math, random, sys, time
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Optional
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F


def safe_load(path, map_location="cpu"):
    try:
        return torch.load(path, map_location=map_location, weights_only=False)
    except TypeError:
        return torch.load(path, map_location=map_location)


def set_seed(seed):
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available(): torch.cuda.manual_seed_all(seed)


def capture_rng_state():
    out={"python":random.getstate(),"numpy":np.random.get_state(),"torch":torch.get_rng_state()}
    if torch.cuda.is_available(): out["cuda"]=torch.cuda.get_rng_state_all()
    return out


def setup_logging(path):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(message)s",
        handlers=[logging.FileHandler(path,mode="a"),logging.StreamHandler(sys.stdout)],force=True)


def log(*x): logging.info(" ".join(str(z) for z in x))


@dataclass
class Config:
    seed:int=32
    num_steps:int=20
    reference_sigma:float=0.15
    bridge_eps:float=1e-3
    base_channels:int=32
    total_imf:int=7
    fork_imf:int=3
    inner_steps:int=800
    batch_size:int=8
    rollout_batch_size:int=8
    lr:float=2e-4
    grad_clip:float=5.0
    eval_mc:int=8
    eval_sens_mc:int=4
    eval_batch_size:int=8
    finite_delta:float=0.25


ENDPOINT_SPLITS=["train","test_seen","test_id","test_ood_near","test_ood_far"]
RESP_FILES={
    "test_seen":"response_eval_seen.pt",
    "test_id":"response_eval_id.pt",
    "test_ood_near":"response_eval_ood_near.pt",
    "test_ood_far":"response_eval_ood_far.pt",
}


def load_dataset(data_dir):
    data_dir=Path(data_dir); endpoint={}; response={}
    for split in ENDPOINT_SPLITS:
        o=safe_load(data_dir/f"{split}.pt")
        for k in ["x0_norm","xT_norm","a","x0","xT"]:
            if k not in o: raise RuntimeError(f"{split}: missing {k}")
        endpoint[split]={
            "x0":o["x0_norm"].float(),"x1":o["xT_norm"].float(),"a":o["a"].float(),
            "x0_raw":o["x0"].float(),"x1_raw":o["xT"].float(),
        }
    for split,fn in RESP_FILES.items():
        o=safe_load(data_dir/fn)
        for k in ["x0_norm","a","direction","Jv_star_norm","finite_response_norm"]:
            if k not in o: raise RuntimeError(f"{fn}: missing {k}")
        response[split]={
            "x0":o["x0_norm"].float(),"a":o["a"].float(),"direction":o["direction"].float(),
            "Jv_star":o["Jv_star_norm"].float(),"finite_response":o["finite_response_norm"].float(),
        }
    metadata=json.load(open(data_dir/"metadata.json"))
    shape=tuple(endpoint["train"]["x0"].shape[1:])
    if shape!=(2,128,128): raise RuntimeError(f"Expected (2,128,128), got {shape}")
    if endpoint["train"]["a"].shape[1]!=3: raise RuntimeError("Expected intervention dim 3")
    return endpoint,response,metadata,shape,3


class Block(nn.Module):
    def __init__(self,ci,co):
        super().__init__(); g=min(8,co)
        while co%g: g-=1
        self.net=nn.Sequential(
            nn.Conv2d(ci,co,3,padding=1),nn.GroupNorm(g,co),nn.SiLU(),
            nn.Conv2d(co,co,3,padding=1),nn.GroupNorm(g,co),nn.SiLU())
    def forward(self,x): return self.net(x)


class ConditionalUNetDrift(nn.Module):
    def __init__(self,base=32):
        super().__init__(); b=base
        self.e1=Block(6,b); self.d1=nn.Conv2d(b,2*b,4,2,1)
        self.e2=Block(2*b,2*b); self.d2=nn.Conv2d(2*b,4*b,4,2,1)
        self.e3=Block(4*b,4*b); self.d3=nn.Conv2d(4*b,8*b,4,2,1)
        self.mid=Block(8*b,8*b)
        self.u3=nn.ConvTranspose2d(8*b,4*b,4,2,1); self.c3=Block(8*b,4*b)
        self.u2=nn.ConvTranspose2d(4*b,2*b,4,2,1); self.c2=Block(4*b,2*b)
        self.u1=nn.ConvTranspose2d(2*b,b,4,2,1); self.c1=Block(2*b,b)
        self.out=nn.Conv2d(b,2,1)
    def forward(self,x,a,t):
        B,_,H,W=x.shape
        if t.ndim==1: t=t[:,None]
        t=t.reshape(B,-1)[:,:1]
        cond=torch.cat([a,t],1)[:,:,None,None].expand(-1,-1,H,W)
        e1=self.e1(torch.cat([x,cond],1)); e2=self.e2(self.d1(e1)); e3=self.e3(self.d2(e2))
        m=self.mid(self.d3(e3))
        y=self.c3(torch.cat([self.u3(m),e3],1))
        y=self.c2(torch.cat([self.u2(y),e2],1))
        y=self.c1(torch.cat([self.u1(y),e1],1))
        return self.out(y)


class ConditionalFieldDSBM:
    def __init__(self,cfg,state_shape,intervention_dim,device):
        self.cfg=cfg; self.state_shape=tuple(state_shape); self.intervention_dim=intervention_dim; self.device=device
        self.net_f=ConditionalUNetDrift(cfg.base_channels).to(device)
        self.net_b=ConditionalUNetDrift(cfg.base_channels).to(device)
        self.nets={"f":self.net_f,"b":self.net_b}; self.prev_fb:Optional[str]=None
    def state_dict(self): return {"net_f":self.net_f.state_dict(),"net_b":self.net_b.state_dict(),"prev_fb":self.prev_fb}
    def load_state_dict(self,s):
        self.net_f.load_state_dict(s["net_f"]); self.net_b.load_state_dict(s["net_b"]); self.prev_fb=s.get("prev_fb")
    def get_train_tuple(self,z0,z1,a,fb):
        B=z0.shape[0]; eps=self.cfg.bridge_eps
        t=torch.rand(B,1,1,1,device=z0.device)*(1-2*eps)+eps; noise=torch.randn_like(z0)
        zt=(1-t)*z0+t*z1+self.cfg.reference_sigma*torch.sqrt(t*(1-t))*noise
        if fb=="f": target=(z1-z0)-self.cfg.reference_sigma*torch.sqrt(t/(1-t))*noise
        elif fb=="b": target=-(z1-z0)-self.cfg.reference_sigma*torch.sqrt((1-t)/t)*noise
        else: raise ValueError(fb)
        return zt,a,t.reshape(B,1),target
    def _noise_bank(self,x,nsteps=None):
        n=self.cfg.num_steps if nsteps is None else int(nsteps)
        return [torch.randn_like(x) for _ in range(n)]
    @torch.no_grad()
    def sample_sde(self,xstart,a,fb="f",noise_bank=None,nsteps=None):
        n=self.cfg.num_steps if nsteps is None else int(nsteps); dt=1.0/n; x=xstart.clone(); net=self.nets[fb]
        if noise_bank is None: noise_bank=self._noise_bank(x,n)
        for k in range(n):
            tv=k/n if fb=="f" else 1-k/n
            t=torch.full((x.shape[0],1),tv,device=x.device,dtype=x.dtype)
            x=x+dt*net(x,a,t)+self.cfg.reference_sigma*math.sqrt(dt)*noise_bank[k]
        return x
    @torch.no_grad()
    def sample_sde_chunked(self,x,a,fb):
        outs=[]
        for s in range(0,x.shape[0],self.cfg.rollout_batch_size):
            e=min(x.shape[0],s+self.cfg.rollout_batch_size)
            outs.append(self.sample_sde(x[s:e],a[s:e],fb=fb).detach())
        return torch.cat(outs,0)
    @torch.no_grad()
    def regenerate_coupling(self,data):
        x0=data["x0"].to(self.device); x1=data["x1"].to(self.device); a=data["a"].to(self.device)
        if self.prev_fb is None: return x0,x1,a
        if self.prev_fb=="f": z0=x0; z1=self.sample_sde_chunked(x0,a,"f")
        else: z0=self.sample_sde_chunked(x1,a,"b"); z1=x1
        return z0.detach(),z1.detach(),a
    def train_pass(self,data,fb):
        z0,z1,a=self.regenerate_coupling(data); net=self.nets[fb]; net.train()
        opt=torch.optim.AdamW(net.parameters(),lr=self.cfg.lr,weight_decay=1e-5); n=z0.shape[0]; recent=[]
        for step in range(1,self.cfg.inner_steps+1):
            b=min(self.cfg.batch_size,n); idx=torch.randint(0,n,(b,),device=self.device)
            zt,ba,t,target=self.get_train_tuple(z0[idx],z1[idx],a[idx],fb); pred=net(zt,ba,t)
            loss=F.mse_loss(pred,target)
            opt.zero_grad(set_to_none=True); loss.backward(); torch.nn.utils.clip_grad_norm_(net.parameters(),self.cfg.grad_clip); opt.step()
            recent.append(float(loss.detach().cpu())); recent=recent[-100:]
            re=max(50,self.cfg.inner_steps//5)
            if step==1 or step%re==0 or step==self.cfg.inner_steps:
                log(f"{fb} step {step:5d}/{self.cfg.inner_steps}",f"bridge={float(loss.detach().cpu()):.6f}")
        self.prev_fb=fb; return {"bridge_loss_last100":float(np.mean(recent))}
    def tangent_direction_rollout(self,x0,a,direction,noise_bank=None):
        dt=1.0/self.cfg.num_steps; x=x0.clone(); R=torch.zeros_like(x)
        if noise_bank is None: noise_bank=self._noise_bank(x)
        for k in range(self.cfg.num_steps):
            t=torch.full((x.shape[0],1),k/self.cfg.num_steps,device=x.device,dtype=x.dtype)
            def drift_fn(xi,ai): return self.net_f(xi,ai,t)
            drift,td=torch.autograd.functional.jvp(drift_fn,(x,a),(R,direction),create_graph=False,strict=False)
            x=(x+dt*drift+self.cfg.reference_sigma*math.sqrt(dt)*noise_bank[k]).detach()
            R=(R+dt*td).detach()
        return R


def norm_stats(metadata,device):
    m=torch.tensor(metadata["normalization"]["state_mean_per_channel"],device=device).view(1,2,1,1)
    s=torch.tensor(metadata["normalization"]["state_std_per_channel"],device=device).view(1,2,1,1)
    return m,s


@torch.no_grad()
def endpoint_metrics(model,data,cfg,device,metadata):
    n=data["x0"].shape[0]; preds=[]
    for s in range(0,n,cfg.eval_batch_size):
        e=min(n,s+cfg.eval_batch_size); x0=data["x0"][s:e].to(device); a=data["a"][s:e].to(device); acc=torch.zeros_like(x0)
        for _ in range(cfg.eval_mc): acc+=model.sample_sde(x0,a,"f")
        preds.append((acc/cfg.eval_mc).cpu())
    pred=torch.cat(preds); true=data["x1"]; diff=pred-true
    rel=(torch.linalg.vector_norm(diff.reshape(n,-1),dim=1)/torch.linalg.vector_norm(true.reshape(n,-1),dim=1).clamp_min(1e-8)).mean()
    rmse=torch.sqrt((diff**2).mean()); m,std=norm_stats(metadata,"cpu"); raw=torch.sqrt((((pred*std+m)-data["x1_raw"])**2).mean())
    return {"field_rmse_norm":float(rmse),"field_rel_l2":float(rel),"field_rmse_raw":float(raw)}


def sensitivity_metrics(model,data,cfg,device,metadata):
    n=min(cfg.eval_batch_size,data["x0"].shape[0]); x0=data["x0"][:n].to(device); a=data["a"][:n].to(device)
    d=data["direction"][:n].to(device); true=data["Jv_star"][:n].to(device); preds=[]; path=[]
    with torch.enable_grad():
        for _ in range(cfg.eval_sens_mc):
            p=model.tangent_direction_rollout(x0,a,d); preds.append(p.detach()); path.append(((p.detach()-true)**2).mean())
    pred=torch.stack(preds).mean(0); diff=pred-true
    rel=(torch.linalg.vector_norm(diff.reshape(n,-1),dim=1)/torch.linalg.vector_norm(true.reshape(n,-1),dim=1).clamp_min(1e-8)).mean()
    rmse=torch.sqrt((diff**2).mean()); prmse=torch.sqrt(torch.stack(path).mean()); _,std=norm_stats(metadata,device)
    raw=torch.sqrt(((diff*std)**2).mean())
    return {"directional_j_rel_error":float(rel.cpu()),"directional_j_rmse_norm":float(rmse.cpu()),
            "directional_j_pathwise_rmse_norm":float(prmse.cpu()),"directional_j_rmse_raw":float(raw.cpu())}


@torch.no_grad()
def finite_metrics(model,data,cfg,device,metadata):
    n=min(cfg.eval_batch_size,data["x0"].shape[0]); x0=data["x0"][:n].to(device); a=data["a"][:n].to(device)
    d=data["direction"][:n].to(device); true=data["finite_response"][:n].to(device); changes=[]
    for _ in range(cfg.eval_mc):
        nb=model._noise_bank(x0); y0=model.sample_sde(x0,a,"f",noise_bank=nb); y1=model.sample_sde(x0,a+cfg.finite_delta*d,"f",noise_bank=nb); changes.append(y1-y0)
    pred=torch.stack(changes).mean(0); diff=pred-true
    rel=(torch.linalg.vector_norm(diff.reshape(n,-1),dim=1)/torch.linalg.vector_norm(true.reshape(n,-1),dim=1).clamp_min(1e-8)).mean()
    rmse=torch.sqrt((diff**2).mean()); _,std=norm_stats(metadata,device); raw=torch.sqrt(((diff*std)**2).mean())
    return {"finite_response_rmse_norm":float(rmse.cpu()),"finite_response_rel_l2":float(rel.cpu()),"finite_response_rmse_raw":float(raw.cpu())}


def evaluate_split(split,model,endpoint,response,cfg,device,metadata):
    out=endpoint_metrics(model,endpoint,cfg,device,metadata); out.update(sensitivity_metrics(model,response,cfg,device,metadata)); out.update(finite_metrics(model,response,cfg,device,metadata))
    log(split,json.dumps(out,indent=2)); return out


@torch.no_grad()
def convergence(model,train,cfg,device):
    n=min(8,train["x0"].shape[0]); x0=train["x0"][:n].to(device); a=train["a"][:n].to(device); x1=train["x1"][:n].to(device); acc=torch.zeros_like(x1)
    for _ in range(min(cfg.eval_mc,2)): acc+=model.sample_sde(x0,a,"f")
    pred=acc/min(cfg.eval_mc,2); return float(torch.sqrt(((pred-x1)**2).mean()).cpu())


def save_ckpt(path,model,cfg,imf,state_shape,intervention_dim):
    torch.save({"model":model.state_dict(),"config":asdict(cfg),"imf":imf,"state_shape":list(state_shape),
                "intervention_dim":intervention_dim,"rng_state":capture_rng_state()},path)


def parse_args():
    p=argparse.ArgumentParser()
    p.add_argument("--data-dir",default="runs/pdebench_reaction_diffusion_official")
    p.add_argument("--run-root",default="runs/pdebench_rd_conditional")
    p.add_argument("--seed",type=int,default=32); p.add_argument("--total-imf",type=int,default=7); p.add_argument("--fork-imf",type=int,default=3)
    p.add_argument("--inner-steps",type=int,default=800); p.add_argument("--num-steps",type=int,default=20); p.add_argument("--reference-sigma",type=float,default=0.15)
    p.add_argument("--base-channels",type=int,default=32); p.add_argument("--batch-size",type=int,default=8); p.add_argument("--rollout-batch-size",type=int,default=8)
    p.add_argument("--lr",type=float,default=2e-4); p.add_argument("--eval-mc",type=int,default=8); p.add_argument("--eval-sens-mc",type=int,default=4); p.add_argument("--eval-batch-size",type=int,default=8)
    p.add_argument("--device",default=None); p.add_argument("--quick",action="store_true")
    return p.parse_args()


def main():
    a=parse_args(); cfg=Config(seed=a.seed,num_steps=a.num_steps,reference_sigma=a.reference_sigma,base_channels=a.base_channels,total_imf=a.total_imf,fork_imf=a.fork_imf,
        inner_steps=a.inner_steps,batch_size=a.batch_size,rollout_batch_size=a.rollout_batch_size,lr=a.lr,eval_mc=a.eval_mc,eval_sens_mc=a.eval_sens_mc,eval_batch_size=a.eval_batch_size)
    if cfg.fork_imf>cfg.total_imf: raise ValueError("fork-imf must be <= total-imf")
    if a.quick:
        cfg.total_imf=1; cfg.fork_imf=1; cfg.inner_steps=10; cfg.num_steps=3; cfg.batch_size=2; cfg.rollout_batch_size=2; cfg.eval_mc=1; cfg.eval_sens_mc=1; cfg.eval_batch_size=1; cfg.base_channels=min(cfg.base_channels,16)
    device=torch.device(a.device if a.device else ("cuda" if torch.cuda.is_available() else "cpu")); set_seed(cfg.seed)
    endpoint,response,metadata,state_shape,intervention_dim=load_dataset(a.data_dir); cfg.finite_delta=float(metadata.get("finite_delta",cfg.finite_delta))
    run_dir=Path(a.run_root)/f"seed_{cfg.seed}"; run_dir.mkdir(parents=True,exist_ok=True); setup_logging(run_dir/"conditional_dsbm.log")
    log("PDEBENCH REACTION-DIFFUSION CONDITIONAL DSBM"); log("device",device,"state",state_shape,"config",json.dumps(asdict(cfg)))
    model=ConditionalFieldDSBM(cfg,state_shape,intervention_dim,device)
    log("trainable params",sum(p.numel() for p in list(model.net_f.parameters())+list(model.net_b.parameters())))
    history=[]; t0=time.time()
    for imf in range(1,cfg.total_imf+1):
        log(f"IMF {imf}/{cfg.total_imf} BACKWARD"); b=model.train_pass(endpoint["train"],"b")
        log(f"IMF {imf}/{cfg.total_imf} FORWARD"); f=model.train_pass(endpoint["train"],"f")
        save_ckpt(run_dir/f"imf_{imf}.pt",model,cfg,imf,state_shape,intervention_dim)
        conv=convergence(model,endpoint["train"],cfg,device); history.append({"imf":imf,"backward_bridge_loss_last100":b["bridge_loss_last100"],"forward_bridge_loss_last100":f["bridge_loss_last100"],"train_endpoint_rmse_norm":conv})
        json.dump(history,open(run_dir/"convergence.json","w"),indent=2); log("train endpoint rmse",conv)
    train_seconds=time.time()-t0; model.net_f.eval(); model.net_b.eval(); results={}
    for split in ["test_seen","test_id","test_ood_near","test_ood_far"]: results[split]=evaluate_split(split,model,endpoint[split],response[split],cfg,device,metadata)
    torch.save({"model":model.state_dict(),"config":asdict(cfg),"state_shape":list(state_shape),"intervention_dim":intervention_dim,"metadata":metadata},run_dir/"final_model.pt")
    payload={"method":"conditional_dsbm","benchmark":"pdebench_2d_diffusion_reaction_official","seed":cfg.seed,"config":asdict(cfg),"train_seconds":train_seconds,
             "shared_tangent_fork":str(run_dir/f"imf_{cfg.fork_imf}.pt"),"metrics":results}
    json.dump(payload,open(run_dir/"metrics.json","w"),indent=2)
    rows=[{"method":"conditional_dsbm","seed":cfg.seed,"split":s,**m,"train_seconds":train_seconds} for s,m in results.items()]
    with open(run_dir/"metrics.csv","w",newline="") as fp:
        w=csv.DictWriter(fp,fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    for s,m in results.items(): log(s,"field_rel",f"{m['field_rel_l2']:.4f}","Jv_rel",f"{m['directional_j_rel_error']:.4f}","finite_rel",f"{m['finite_response_rel_l2']:.4f}")
    log("Tangent fork",run_dir/f"imf_{cfg.fork_imf}.pt")


if __name__=="__main__": main()
